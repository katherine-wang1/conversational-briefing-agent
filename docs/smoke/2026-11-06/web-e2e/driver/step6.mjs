import { open, sleep, BASE, SP } from "./lib.mjs";
import fs from "node:fs";
const { ctx, page } = await open();
const phase = () => page.getAttribute('[data-testid="phase"]', "data-phase").catch(() => null);
const waitPhase = async (want, ms) => { const t = Date.now(); while (Date.now() - t < ms) { if ((await phase()) === want) return want; await sleep(200); } return await phase(); };
await page.goto(`${BASE}/#/today`); await waitPhase("ready", 15000);
await page.getByTestId("talk").click(); await waitPhase("playing", 5000); await sleep(3000);
await page.getByRole("button", { name: "Type instead" }).click();
await page.fill('input[placeholder="Type a question"]', process.env.Q || "Why did China block that deal?");
const t0 = Date.now();
await page.getByRole("button", { name: "Send" }).click();
const a = await waitPhase("answering", 30000); const tA = Date.now() - t0;
const back = await waitPhase("playing", 90000);
const fr = await page.evaluate(() => window.__frames.filter(f => f.type === "transcript" || f.type === "resume_brief" || f.type === "error").map(f => f.j));
const r = { typedAnswerPhase: a, msToAnswerAudio: tA, backToBrief: back, frames: fr };
console.log(JSON.stringify(r, null, 1));
fs.writeFileSync(`${SP}/step6${process.env.TAG||""}.json`, JSON.stringify(r, null, 1));
await page.getByTestId("end").click(); await sleep(1500);
await ctx.close();
