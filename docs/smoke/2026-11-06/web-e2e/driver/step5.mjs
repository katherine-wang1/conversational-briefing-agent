import fs from "node:fs";
import { open, sleep, BASE, SP } from "./lib.mjs";
const { ctx, page, log } = await open();
const out = { checks: [] };
const check = (name, ok, detail = "") => { out.checks.push({ name, ok, detail }); console.log(ok ? "  ok  " : "  FAIL", name, detail ? `(${String(detail).slice(0, 300)})` : ""); };
const phase = () => page.getAttribute('[data-testid="phase"]', "data-phase").catch(() => null);
const conv = (e) => page.evaluate(`(() => { const c = window.__conv; return ${e}; })()`);
const waitPhase = async (want, ms) => { const t = Date.now(); while (Date.now() - t < ms) { if ((await phase()) === want) return want; await sleep(200); } return await phase(); };
await page.goto(`${BASE}/#/today`);
await waitPhase("ready", 15000);
await page.getByTestId("talk").click();
await waitPhase("playing", 5000);
// skip twice to get further in (also exercises Skip against the real backend)
await sleep(2500); await page.getByTestId("skip").click(); await sleep(2500); await page.getByTestId("skip").click(); await sleep(3000);
const idxBefore = await conv("c.state.get().segmentIndex");
check("Skip story moves on (real backend)", idxBefore > 2, `segmentIndex ${idxBefore}`);
await page.reload();
const ph = await waitPhase("ready", 15000);
const idxAfter = await conv("c.state.get().segmentIndex");
const label = await page.textContent('[data-testid="phase"]');
check("Reload: brief still there, resumes at the same sentence", ph === "ready" && idxAfter === idxBefore && /Resume/.test(label), JSON.stringify({ idxBefore, idxAfter, label }));
await page.screenshot({ path: `${SP}/shots/11-resume-after-reload.png` });
await page.getByTestId("talk").click();
await waitPhase("playing", 5000); await sleep(2000);
const ev = await page.evaluate(() => window.__audioEv.filter(e => e.e === "playing").map(e => e.src));
const fr = await page.evaluate(() => window.__frames.filter(f => f.type === "playback").slice(0, 2).map(f => f.j));
check("Playback after reload starts at the saved segment", fr.length > 0 && fr[0].segment_id === `s${String(idxBefore).padStart(3, "0")}`, JSON.stringify({ firstPlayback: fr[0], firstSrc: ev[0] }));
await page.getByTestId("end").click(); await sleep(1500);
out.log = log.filter(l => !/media|today/.test(l));
fs.writeFileSync(`${SP}/step5.json`, JSON.stringify(out, null, 1));
await ctx.close();
