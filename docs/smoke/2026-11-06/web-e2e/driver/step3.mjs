import fs from "node:fs";
import { open, sleep, BASE, SP } from "./lib.mjs";
const Q = process.env.Q || "Who is leading that, and what's the timeline?";
const { ctx, page, log } = await open();
const out = { checks: [] };
const check = (name, ok, detail = "") => { out.checks.push({ name, ok, detail }); console.log(ok ? "  ok  " : "  FAIL", name, detail ? `(${String(detail).slice(0, 300)})` : ""); };
const phase = () => page.getAttribute('[data-testid="phase"]', "data-phase").catch(() => null);
const conv = (e) => page.evaluate(`(() => { const c = window.__conv; return ${e}; })()`);
const waitPhase = async (want, ms) => { const t = Date.now(); while (Date.now() - t < ms) { const p = await phase(); if ((Array.isArray(want) ? want : [want]).includes(p)) return p; await sleep(200); } return await phase(); };
await page.goto(`${BASE}/#/today`);
check("Today screen ready after reload", (await waitPhase("ready", 20000)) === "ready");
// 1. play
await page.getByTestId("talk").click();
check("phase playing", (await waitPhase("playing", 10000)) === "playing");
await sleep(9000);
const ev1 = await page.evaluate(() => window.__audioEv);
const playing = ev1.filter((e) => e.e === "playing").length, ended = ev1.filter((e) => e.e === "ended").length, errs = ev1.filter((e) => e.e === "error");
const ct = await page.evaluate(() => { const els = [...document.querySelectorAll("audio")]; return els.map(a => ({ ct: a.currentTime, paused: a.paused, src: a.currentSrc.slice(0, 40), err: a.error && a.error.code })); });
check("brief segments play in order with no decode errors", playing >= 2 && ended >= 1 && errs.length === 0, JSON.stringify({ playing, ended, errs: errs.length, segIndex: await conv("c.state.get().segmentIndex") }));
const md = await page.evaluate(() => navigator.mediaSession && navigator.mediaSession.metadata ? { title: navigator.mediaSession.metadata.title, artist: navigator.mediaSession.metadata.artist, state: navigator.mediaSession.playbackState } : null);
check("Media Session metadata set", !!md && !!md.title, JSON.stringify(md));
const t1 = await conv("c.out ? c.out.positionMs() : null"); await sleep(1500); const t2 = await conv("c.out ? c.out.positionMs() : null");
check("currentTime advancing", t1 !== null && t2 !== null && t2 !== t1, `${t1} -> ${t2}`);
await page.screenshot({ path: `${SP}/shots/04-playing.png` });
const fr = await page.evaluate(() => window.__frames);
check("WebSocket: hello sent, server READY then PLAYING_BRIEF", fr.some(f => f.type === "hello") && fr.some(f => f.type === "state" && f.j.state === "PLAYING_BRIEF"), `ws=${await page.evaluate(() => window.__wsUrl)}`);
// 2. interrupt (button), browser STT (stubbed), second tap = done
await page.evaluate((q) => { window.__sttText = q; }, Q);
const tI = Date.now();
await page.getByTestId("interrupt-btn").click();
check("interrupt -> listening", (await waitPhase("listening", 3000)) === "listening", `interrupt->pause ${await conv("c.state.get().lastInterruptMs")} ms`);
const fr2 = await page.evaluate(() => window.__frames.filter(f => f.type === "interrupt").map(f => f.j));
check("interrupt frame has segment_id + offset_ms", fr2.length && fr2[0].segment_id && Number.isInteger(fr2[0].offset_ms), JSON.stringify(fr2[0]));
await sleep(1200);
await page.screenshot({ path: `${SP}/shots/05-listening.png` });
await page.getByTestId("talk").click(); // "I'm done"
const tSent = Date.now();
const p3 = await waitPhase(["thinking", "answering"], 5000);
check("utterance sent -> thinking/answering", ["thinking", "answering"].includes(p3), p3);
// 3. answer
const ansPhase = await waitPhase("answering", 30000);
const tAns = Date.now();
check("answer audio starts (phase answering)", ansPhase === "answering", `end-of-speech->audio: client ${await conv("c.state.get().lastLatencyMs")} ms, wall ${tAns - tSent} ms`);
await sleep(1500);
await page.screenshot({ path: `${SP}/shots/06-answering.png` });
const backTo = await waitPhase("playing", 90000);
const fr3 = await page.evaluate(() => window.__frames);
const chunks = fr3.filter(f => f.type === "tts_chunk");
const tx = fr3.filter(f => f.type === "transcript").map(f => ({ role: f.j.role, text: f.j.text, cites: f.j.citations, final: f.j.final }));
const answerEv = (await page.evaluate(() => window.__audioEv)).filter(e => e.t > tAns - 3000 && e.t < Date.now());
check("tts_chunks received and played", chunks.length > 0 && answerEv.some(e => e.e === "playing"), JSON.stringify({ chunks: chunks.length, fmt: chunks[0] && chunks[0].j.format, seqs: chunks.map(c => c.j.seq) }));
out.answer = tx.filter(t => t.role === "agent");
out.user = tx.filter(t => t.role === "user");
check("resume_brief received and brief playing again", backTo === "playing" && fr3.some(f => f.type === "resume_brief"), JSON.stringify(fr3.filter(f => f.type === "resume_brief").map(f => f.j)));
out.resumeAtSeg = await conv("c.state.get().segmentIndex");
// 4. let it play to the end (open floor), then end
const endPh = await waitPhase("open_floor", 240000);
const fr4 = await page.evaluate(() => window.__frames);
check("brief plays to the end -> open_floor; completed playback sent; server OPEN_FLOOR", endPh === "open_floor" && fr4.some(f => f.type === "playback" && f.j.completed) && fr4.some(f => f.type === "state" && f.j.state === "OPEN_FLOOR"), JSON.stringify({ endPh, completedFrames: fr4.filter(f => f.type === "playback" && f.j.completed).length, states: fr4.filter(f => f.type === "state").map(f => f.j.state) }));
const allEv = await page.evaluate(() => window.__audioEv);
out.audioSummary = { playing: allEv.filter(e => e.e === "playing").length, ended: allEv.filter(e => e.e === "ended").length, error: allEv.filter(e => e.e === "error").length, errors: allEv.filter(e => e.e === "error").slice(0, 3) };
await page.screenshot({ path: `${SP}/shots/07-open-floor.png` });
await page.getByTestId("end").click();
const endP = await waitPhase("ended", 5000);
check("End -> ended (rating sheet)", endP === "ended");
await sleep(800);
await page.screenshot({ path: `${SP}/shots/08-rating.png` });
out.sessionId = await conv("c.state.get().sessionId");
out.frames = fr4.map(f => ({ dir: f.dir, type: f.type, state: f.j && f.j.state, seg: f.j && f.j.segment_id, completed: f.j && f.j.completed, t: f.t })).filter(f => f.type !== "playback" || f.completed);
out.log = log.filter(l => !/media/.test(l));
fs.writeFileSync(`${SP}/step3.json`, JSON.stringify(out, null, 1));
await ctx.close();
